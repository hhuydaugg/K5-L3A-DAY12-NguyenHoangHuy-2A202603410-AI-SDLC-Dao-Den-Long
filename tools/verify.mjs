#!/usr/bin/env node
// Re-runnable evidence: tests + every headless scenario + determinism + full-night timing.
//   npm run verify -- phase-1        writes docs/proof/phase-1/  (never edit those files by hand)
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, mkdtempSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { cpus, platform, release, tmpdir, totalmem } from "node:os";
import { join } from "node:path";
import { NIGHTS } from "../src/sim.js";

const phase = process.argv[2] ?? "local";
const out = join("docs", "proof", phase);
mkdirSync(join(out, "scenarios"), { recursive: true });
const big = mkdtempSync(join(tmpdir(), "ddl-verify-")); // long runs stay out of git: only hashes/timings are reported
const node = (args) => spawnSync(process.execPath, args, { encoding: "utf8" });
const machine = `${platform()} ${release()} · ${cpus()[0]?.model} x${cpus().length} · ${Math.round(totalmem() / 2 ** 30)} GB · node ${process.version}`;
const report = [`# Verify ${phase}`, "", `Generated by \`npm run verify -- ${phase}\` on ${new Date().toISOString()}`, `Machine: ${machine}`, ""];

const t = node(["--test"]);
writeFileSync(join(out, "tests.txt"), t.stdout + t.stderr);
const summary = (t.stdout.match(/^# (tests|pass|fail) \d+/gm) ?? []).join(" · ");
report.push(`## Tests (\`npm test\`) — exit ${t.status}`, "", summary, "", "Full output: tests.txt", "");

report.push("## Headless scenarios (tests/scenarios)", "", "| scenario | night | end | key events |", "|---|---|---|---|");
const SC = "tests/scenarios";
const names = [...new Set(readdirSync(SC).filter((f) => !f.startsWith("bad_") && !f.startsWith("not_"))
  .map((f) => f.replace(/\.(scenario|inputs)\.json$/, "")))].sort();
for (const name of names) {
  const meta = JSON.parse(readFileSync(join(SC, `${name}.${readdirSync(SC).includes(`${name}.scenario.json`) ? "scenario" : "inputs"}.json`), "utf8"));
  const night = String(meta.night ?? 1);
  const args = ["src/headless.mjs", "--seed", "7", "--night", night, "--ticks", "2400", "--out", join(out, "scenarios", `${name}.jsonl`)];
  for (const kind of ["scenario", "inputs"]) {
    if (readdirSync(SC).includes(`${name}.${kind}.json`)) args.push(`--${kind}`, join(SC, `${name}.${kind}.json`));
  }
  const r = node(args);
  const lines = r.status === 0 ? readFileSync(join(out, "scenarios", `${name}.jsonl`), "utf8").trim().split("\n").map((l) => JSON.parse(l)) : [];
  const ev = lines.filter((l) => l.type === "event").map((e) => `${e.tick}:${e.name}`);
  const end = lines.at(-1);
  report.push(`| ${name} | ${night} | ${end ? `${end.state} · ticks ${end.ticks} · score ${end.score}` : `exit ${r.status}: ${r.stderr.trim()}`} | ${ev.slice(0, 8).join(", ")}${ev.length > 8 ? ` … (+${ev.length - 8})` : ""} |`);
}

report.push("", "## Determinism (same seed + inputs, run twice, sha256 of the JSONL)", "");
for (const night of NIGHTS) {
  const hashes = [0, 1].map((i) => {
    const f = join(big, `determinism_n${night}_${i}.jsonl`);
    const r = node(["src/headless.mjs", "--seed", "42", "--night", String(night), "--ticks", "6000", "--inputs", join(SC, "default_night.inputs.json"), "--out", f]);
    return r.status === 0 ? createHash("sha256").update(readFileSync(f)).digest("hex").slice(0, 16) : `exit ${r.status}`;
  });
  report.push(`- night ${night}: ${hashes.join(" vs ")} → ${hashes[0] === hashes[1] ? "IDENTICAL" : "DIFFERENT"}`);
}

report.push("", "## Full night timing (21600 ticks requested, contract limit 30 s)", "");
for (const night of NIGHTS) {
  const t0 = process.hrtime.bigint();
  const r = node(["src/headless.mjs", "--seed", "3", "--night", String(night), "--ticks", "21600",
    "--scenario", join(SC, "immortal_full_night.scenario.json"), "--out", join(big, `full_night_n${night}.jsonl`)]);
  const s = Number(process.hrtime.bigint() - t0) / 1e9;
  const end = r.status === 0 ? readFileSync(join(big, `full_night_n${night}.jsonl`), "utf8").trim().split("\n").at(-1) : r.stderr.trim();
  report.push(`- night ${night}: ${s.toFixed(2)} s · ${end}`);
}
writeFileSync(join(out, "README.md"), report.join("\n") + "\n");
console.log(report.join("\n"));
process.exit(t.status);
